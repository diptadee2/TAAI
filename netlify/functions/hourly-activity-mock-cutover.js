// Scheduled function (see netlify.toml) — runs every 15 minutes and,
// once past a fixed deadline, subtracts the exact known mock-data
// baseline back out of pomo_hourly_activity, then never runs again.
//
// pomo_hourly_activity was seeded with a realistic-looking synthetic
// pattern for launch (2026-09-21) — the Today card's "Activity by hour"
// chart is meant to be looked at, and it would have sat completely empty
// for days otherwise, since it only starts filling in from real sessions
// completed after this feature ships. Direct instruction: "use the mock
// data till 7pm tomorrow and then update it to the real data calculated
// in between till forever."
//
// The subtraction (not a wholesale reset to whatever's been credited
// since) is deliberate — real students' sessions have been incrementing
// these SAME 24 rows on top of the mock baseline the whole time between
// launch and the cutover (increment_hourly_activity has no way to tell a
// "real" completion from a "mock seed" one, nor should it), so the only
// way to recover just the real contribution is to know the exact
// baseline that was seeded and subtract it back out — not overwrite the
// rows with a fresh read of "whatever's credited since," which would
// lose everything real that accumulated in between too.
//
// MOCK_BASELINE_BY_HOUR is generated by the *exact same formula* the
// original seeding script used (a synthetic quiet-overnight /
// morning-bump / evening-peak pattern), reproduced here rather than
// hand-transcribed, so there's no risk of a transcription error between
// what was actually inserted and what this subtracts back out.
import { getSupabase, json } from './lib/supabase.js';

// 7:00 PM IST, 2026-09-22 (the day after this feature's launch day).
const CUTOVER_AT = new Date('2026-09-22T13:30:00.000Z').getTime();

function mockBaselineForHour(h) {
  let minutes;
  if (h >= 0 && h <= 4) minutes = 15;
  else if (h === 5) minutes = 60;
  else if (h >= 6 && h <= 8) minutes = 380 + (h - 6) * 90;
  else if (h === 9) minutes = 520;
  else if (h >= 10 && h <= 13) minutes = 300 - (h - 10) * 30;
  else if (h >= 14 && h <= 16) minutes = 260 + (h - 14) * 40;
  else if (h === 17) minutes = 420;
  else if (h >= 18 && h <= 22) minutes = 700 + (h - 18) * 180;
  else minutes = 900 - (h - 22) * 300; // h === 23
  return { minutes, sessionCount: Math.round(minutes / 27) };
}

export async function handler() {
  if (Date.now() < CUTOVER_AT) {
    return json(200, { ok: true, skipped: 'before cutover', cutoverAt: new Date(CUTOVER_AT).toISOString() });
  }

  const supabase = getSupabase();

  const { data: flag, error: flagError } = await supabase
    .from('hourly_activity_cutover')
    .select('done')
    .eq('id', 1)
    .maybeSingle();
  if (flagError) return json(500, { error: flagError.message });
  if (flag && flag.done) {
    return json(200, { ok: true, skipped: 'already done' });
  }

  // Claim the cutover FIRST, via an atomic insert-or-update that only
  // succeeds the first time — this is what actually makes the operation
  // safe against two overlapping invocations both passing the read-only
  // check above (a real possibility: this runs every 15 minutes, and a
  // slow invocation could still be in flight when the next one starts).
  // ON CONFLICT DO UPDATE ... WHERE done = false means a second racing
  // call's UPDATE matches zero rows once the first has already flipped
  // it to true, so .select() on it comes back empty and that caller
  // knows to skip the subtraction below.
  const { data: claim, error: claimError } = await supabase
    .rpc('claim_hourly_activity_cutover')
    .maybeSingle();
  if (claimError) return json(500, { error: claimError.message });
  if (!claim || !claim.claimed) {
    return json(200, { ok: true, skipped: 'lost the claim race — another invocation is handling it' });
  }

  const results = [];
  for (let h = 0; h < 24; h++) {
    const { minutes, sessionCount } = mockBaselineForHour(h);
    const { data: row, error: rowError } = await supabase
      .from('pomo_hourly_activity')
      .select('session_count, total_minutes')
      .eq('hour', h)
      .maybeSingle();
    if (rowError) { results.push({ hour: h, error: rowError.message }); continue; }
    if (!row) { results.push({ hour: h, skipped: 'no row' }); continue; }

    const newMinutes = Math.max(0, row.total_minutes - minutes);
    const newSessions = Math.max(0, row.session_count - sessionCount);
    const { error: updateError } = await supabase
      .from('pomo_hourly_activity')
      .update({ session_count: newSessions, total_minutes: newMinutes, updated_at: new Date().toISOString() })
      .eq('hour', h);
    if (updateError) { results.push({ hour: h, error: updateError.message }); continue; }
    results.push({ hour: h, before: row, subtracted: { minutes, sessionCount }, after: { session_count: newSessions, total_minutes: newMinutes } });
  }

  return json(200, { ok: true, cutoverPerformed: true, results });
}
